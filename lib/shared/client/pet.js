import {
  getFeatures,
  subscribeFeatures,
  menuLimit,
} from "../feature-registry.js";
import { renderPanels } from "./render-panels.js";
import { usePetState } from "./use-pet-state.js";
import { useTaskPresence } from "./use-task-presence.js";
import { usePetLayout } from "./use-pet-layout.js";
import { usePetMotion } from "./use-pet-motion.js";
import { usePetConfig } from "./use-pet-config.js";
import { usePetData } from "./use-pet-data.js";
import { usePetMenu } from "./use-pet-menu.js";
import { usePetPointer } from "./use-pet-pointer.js";
import { useCareActions } from "./use-care-actions.js";
import { renderOrbs } from "./render-orbs.js";
import { createPanelParts } from "./panel-parts.js";
import { renderMascot } from "./render-mascot.js";
/**
 * @description Compose mascot state, behavior and feature panels.
 * @param {object} dependencies Explicit runtime and state dependencies.
 * @returns {object} Public values for the composing component.
 */
export function createPet({
  usePreferences,
  useRef,
  useEffect,
  DEFAULTS,
  IDLE,
  useState,
  FEATURE_REGISTRY: BUILTIN_FEATURES,
  React,
  ensureTaskRuntime,
  clamp,
  useLayoutEffect,
  liveViewport,
  bubbleOutline,
  useCallback,
  readStore,
  POS_KEY,
  writeStore,
  ASSET_BASE,
  pick,
  taskRuntime,
  injectCss,
  SET_KEY,
  I18N,
  normalizeConfig,
  greetingFor,
  GROW_KEY,
  localHour,
  controls,
  layoutFor,
  LABEL_GAP,
  HINT_KEY,
  DRAG_THRESHOLD,
  t,
  ICONS,
  h,
  fieldLabel,
  weatherIcon,
  LocalClock,
  icon,
  PanelSelect,
  SchedulerSettings,
  RealtimeSettings,
  PREF_DEFAULTS,
}) {
  return function Pet() {
    const {
      prefs,
      locale,
      update: updatePrefs,
      theme,
      reduced,
    } = usePreferences();
    const [extensions, setExtensions] = useState(getFeatures);
    useEffect(() => subscribeFeatures(setExtensions), []);
    const FEATURE_REGISTRY = React.useMemo(
      () => [
        ...BUILTIN_FEATURES.filter(
          (feature) => feature.key !== "github" || prefs.showGitHub,
        ),
        ...extensions.map((feature) => ({
          ...feature,
          icon: icon([h("path", { key: feature.id, d: feature.iconPath })]),
        })),
      ],
      [prefs.showGitHub, extensions],
    );

    const {
      prefsRef,
      quietRef,
      balanceRequest,
      rootRef,
      aRef,
      bRef,
      frontRef,
      currentRef,
      tokenRef,
      timerRef,
      bubbleTimerRef,
      cfgRef,
      dragRef,
      stateRef,
      busyRef,
      lastCareRef,
      lastSeenRef,
      workingSinceRef,
      SMRef,
      GROWRef,
      ARCRef,
      orbGeomRef,
      page,
      setPage,
      pageRef,
      pageTimerRef,
      lastPanelRef,
      visibleCountRef,
      ready,
      setReady,
      tip,
      setTip,
      taskView,
      setTaskView,
      taskHovered,
      setTaskHovered,
      taskFocused,
      setTaskFocused,
      taskVisible,
      setTaskVisible,
      hoverTimer,
      fitSurfacesRef,
      bubble,
      setBubble,
      accordionName,
      panel,
      setPanel,
      inventory,
      setInventory,
      inventoryBusy,
      setInventoryBusy,
      inventoryBusyRef,
      seenDrops,
      pendingResource,
      orbOpen,
      setOrbOpen,
      setViewportTick,
      label,
      setLabel,
      setMeta,
      city,
      setCity,
      balanceView,
      setBalanceView,
      weatherView,
      setWeatherView,
      weatherRequest,
      growthView,
      setGrowthView,
    } = usePetState({
      useRef,
      prefs,
      reduced,
      useEffect,
      DEFAULTS,
      IDLE,
      useState,
      FEATURE_REGISTRY,
      React,
    });
    const { enterTask, leaveTask } = useTaskPresence({
      useEffect,
      ensureTaskRuntime,
      setTaskView,
      taskView,
      setTaskVisible,
      clamp,
      prefs,
      hoverTimer,
      setTaskHovered,
    });
    const { moveTo, applyVisual } = usePetLayout({
      useEffect,
      setViewportTick,
      useLayoutEffect,
      rootRef,
      ARCRef,
      liveViewport,
      cfgRef,
      clamp,
      bubbleOutline,
      dragRef,
      fitSurfacesRef,
      useCallback,
      prefsRef,
      readStore,
      POS_KEY,
      writeStore,
    });
    const { play, speak, scheduleNext } = usePetMotion({
      useRef,
      useCallback,
      aRef,
      bRef,
      frontRef,
      tokenRef,
      ASSET_BASE,
      quietRef,
      currentRef,
      cfgRef,
      setLabel,
      useEffect,
      applyVisual,
      timerRef,
      setBubble,
      prefs,
      reduced,
      prefsRef,
      bubbleTimerRef,
      busyRef,
      pick,
      IDLE,
      stateRef,
      taskRuntime,
    });
    usePetConfig({
      useEffect,
      injectCss,
      readStore,
      SET_KEY,
      setCity,
      ASSET_BASE,
      SMRef,
      GROWRef,
      ARCRef,
      I18N,
      prefsRef,
      cfgRef,
      normalizeConfig,
      applyVisual,
      frontRef,
      aRef,
      setReady,
      play,
      setMeta,
      greetingFor,
      speak,
      setTip,
      timerRef,
      bubbleTimerRef,
    });
    const {
      acceptInventory,
      refreshInventory,
      setFreeInteractions,
      loadBalance,
      loadWeather,
      loadGrowth,
      saveCity,
    } = usePetData({
      useCallback,
      setInventory,
      ASSET_BASE,
      useEffect,
      inventoryBusyRef,
      setInventoryBusy,
      speak,
      GROWRef,
      cfgRef,
      readStore,
      GROW_KEY,
      workingSinceRef,
      busyRef,
      writeStore,
      ready,
      lastSeenRef,
      prefsRef,
      lastCareRef,
      localHour,
      balanceRequest,
      setBalanceView,
      controls,
      city,
      weatherRequest,
      setWeatherView,
      locale,
      I18N,
      panel,
      setGrowthView,
      SET_KEY,
      setCity,
    });
    const { closeOrb, toggleOrb, cyclePage, togglePanel, backToMenu } =
      usePetMenu({
        useCallback,
        cfgRef,
        clamp,
        prefsRef,
        ARCRef,
        layoutFor,
        liveViewport,
        visibleCountRef,
        rootRef,
        LABEL_GAP,
        orbGeomRef,
        setOrbOpen,
        setViewportTick,
        useLayoutEffect,
        orbOpen,
        prefs,
        pageTimerRef,
        pageRef,
        setPage,
        setPanel,
        panel,
        FEATURE_REGISTRY,
        useEffect,
        ready,
        readStore,
        HINT_KEY,
        writeStore,
        speak,
        lastPanelRef,
        loadBalance,
        loadWeather,
        refreshInventory,
        loadGrowth,
        play,
        busyRef,
      });
    const { onPointerDown, onPointerMove, onPointerUp } = usePetPointer({
      ready,
      enterTask,
      rootRef,
      dragRef,
      prefsRef,
      DRAG_THRESHOLD,
      play,
      cfgRef,
      moveTo,
      clamp,
      GROWRef,
      writeStore,
      POS_KEY,
      readStore,
      GROW_KEY,
      busyRef,
      scheduleNext,
      stateRef,
      timerRef,
      pick,
      toggleOrb,
    });
    const { feed, interact } = useCareActions({
      useCallback,
      inventoryBusyRef,
      GROWRef,
      cfgRef,
      closeOrb,
      speak,
      pendingResource,
      readStore,
      GROW_KEY,
      busyRef,
      setInventoryBusy,
      ASSET_BASE,
      acceptInventory,
      pick,
      play,
      loadGrowth,
      prefsRef,
      t,
      useEffect,
      ready,
      inventory,
      seenDrops,
      I18N,
    });
    const cfg = cfgRef.current;
    cfg.ui.arc.pageSize = menuLimit(prefs.menuLimit);
    const { arcCfg, side, geom, stockCount, orbs } = renderOrbs({
      cfg,
      orbGeomRef,
      inventory,
      I18N,
      FEATURE_REGISTRY,
      lastPanelRef,
      togglePanel,
      feed,
      ARCRef,
      page,
      t,
      ICONS,
      cyclePage,
      visibleCountRef,
      h,
      orbOpen,
      closeOrb,
      speak,
    });
    const { disclosure, metric, updatedAt, cityForm, panelHead, panelShell } =
      createPanelParts({
        h,
        ICONS,
        controls,
        accordionName,
        t,
        I18N,
        fieldLabel,
        city,
        saveCity,
        backToMenu,
      });
    const panelEl = renderPanels({
      panel,
      h,
      taskRuntime,
      taskView,
      setPanel,
      rootRef,
      panelShell,
      balanceView,
      panelHead,
      ICONS,
      t,
      loadBalance,
      controls,
      fieldLabel,
      prefs,
      I18N,
      updatedAt,
      weatherView,
      loadWeather,
      weatherIcon,
      metric,
      LocalClock,
      disclosure,
      cityForm,
      growthView,
      loadGrowth,
      refreshInventory,
      inventory,
      inventoryBusy,
      feed,
      stockCount,
      interact,
      icon,
      PanelSelect,
      updatePrefs,
      FEATURE_REGISTRY,
      setFreeInteractions,
      SchedulerSettings,
      RealtimeSettings,
      POS_KEY,
      applyVisual,
      PREF_DEFAULTS,
    });
    return renderMascot({
      cfgRef,
      pageTimerRef,
      onPointerDown,
      onPointerMove,
      onPointerUp,
      taskView,
      taskRuntime,
      taskVisible,
      taskHovered,
      taskFocused,
      panel,
      orbOpen,
      bubble,
      h,
      setOrbOpen,
      setPanel,
      label,
      prefs,
      arcCfg,
      geom,
      rootRef,
      enterTask,
      leaveTask,
      setTaskFocused,
      locale,
      theme,
      reduced,
      side,
      toggleOrb,
      aRef,
      bRef,
      tip,
      orbs,
      panelEl,
      controls,
    });
  };
}
